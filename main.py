# Завершите решение так, чтобы оно разбивало строку на строки по два символа в виде списка/массива (в зависимости от используемого языка). Если строка содержит нечетное количество символов, то пропущенный второй символ в последней паре должен быть заменен символом подчеркивания ('_').

# Примеры:

# * 'abc' =>  ['ab', 'c_']
# * 'abcdef' => ['ab', 'cd', 'ef']


def solution(s):
    if len(s) % 2:
        s += "_"
    return [s[i:i+2] for i in range(0, len(s), 2)]


