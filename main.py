#Если перечислить все натуральные числа меньше 10, кратные 3 или 5, то получим 3, 5, 6 и 9. Сумма этих кратных равна 23.
#Завершите решение так, чтобы оно возвращало сумму всех чисел, кратных 3 или 5, которые меньше переданного числа.
#Кроме того, если число отрицательное, вернуть 0.
#Примечание: Если число кратно одновременно 3 и 5, учитывайте его только один раз .

def solution(number):
    return sum(i for i in range(1, number) if i % 3 == 0 or i % 5 == 0)


# Напишите функцию, которая принимает на вход целое число и возвращает количество битов, равных единице в двоичном представлении этого числа. Гарантируется, что входное число неотрицательно.

def count_bits(n):
    return bin(n).count("1")